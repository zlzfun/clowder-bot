import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { once } from 'node:events';
import { createApp } from '../server/app.js';
import { Store } from '../server/store.js';
import type { AgentProvider, AgentRequest, ProviderKind } from '../shared/types.js';

test('XBot original API: boot shapes, generated avatars, real CRUD, delivery SSE/transcript, group handoff and persistence', async t => {
  const dir = mkdtempSync(join(tmpdir(), 'clowder-xbot-core-'));
  const called: ProviderKind[] = [];
  const runtime = createApp({ dataFile: join(dir, 'state.json'), provider: kind => {
    called.push(kind);
    return { async *stream(request: AgentRequest) {
      const last = request.messages.at(-1)?.content ?? '';
      if (last.includes('fail-now')) throw new Error('expected provider failure');
      yield { type: 'delta', text: '真实桥接回复' };
      yield { type: 'delta', text: '\n<memory scope="bot">本猫记忆</memory>' };
      if (request.bot.name === '宪宪' && request.messages[0]!.content.includes('群聊') && !last.startsWith('协作交接任务')) yield { type: 'delta', text: '\n@砚砚 请检查' };
    } } satisfies AgentProvider;
  } });
  const server = runtime.app.listen(0, '127.0.0.1'); await once(server, 'listening');
  const address = server.address(); assert.ok(address && typeof address !== 'string');
  const base = `http://127.0.0.1:${address.port}/xbot-api`;
  t.after(async () => { await runtime.close(); await new Promise<void>(resolve => server.close(() => resolve())); rmSync(dir, { recursive: true, force: true }); });
  const call = (method: string, path: string, body?: unknown) => fetch(base + path, { method, ...(body === undefined ? {} : { headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) }) });
  const json = async (path: string) => (await call('GET', path)).json() as Promise<any>;
  assert.equal((await json('/session')).authed, true);
  const bots = (await json('/bots')).bots;
  assert.equal(bots.length, 3);
  assert.equal(bots[0].avatar, 'generated'); assert.equal(bots[0].avatar_url, ''); assert.equal(bots[0].avatar_seed, 'cat:ragdoll');
  assert.equal(bots[0].templateId, 'ragdoll');
  assert.equal((await json('/bots/宪宪')).persona_card.id, 'cat-ragdoll');
  assert.equal((await json('/bots/status')).bots[0].bot, '宪宪');
  assert.deepEqual((await json('/bots/宪宪/context')).requests, []);
  assert.equal((await call('POST', '/bots', { name: 'ada', persona: '帮助我写代码' })).status, 200);
  assert.equal((await call('POST', '/bots', { name: 'ada' })).status, 409);
  assert.equal((await call('POST', '/groups', { name: '工作' })).status, 200);
  assert.equal((await call('PATCH', '/bots/ada', { group: '工作', avatar_seed: 'ada#2', description: '开发伙伴' })).status, 200);
  assert.equal((await json('/bots/ada')).avatar_seed, 'ada#2');
  assert.deepEqual((await json('/groups')).folders.find((f: any) => f.name === '工作').bots, ['ada']);
  assert.equal((await call('POST', '/bots/ada/pin', { pinned: true })).status, 200);
  assert.equal((await json('/bots/ada')).pinned, true);
  assert.equal((await call('PUT', '/bots/ada/binding', { provider: 'codex-cli', model: 'default' })).status, 200);
  assert.equal((await json('/bots/ada')).provider, 'codex-cli'); assert.equal((await json('/bots/ada')).model, 'default');
  const response = await call('POST', '/bots/ada/messages', { text: 'hello' });
  assert.match(response.headers.get('content-type')!, /text\/event-stream/);
  const stream = await response.text();
  assert.match(stream, /event: result/); assert.match(stream, /send_message_to_user/); assert.match(stream, /event: done/);
  assert.equal(called.at(-1), 'codex-cli');
  const countBeforeSummary = called.length;
  assert.equal((await call('POST', '/bots/ada/compact')).status, 200);
  assert.equal(called.length, countBeforeSummary + 1);
  assert.equal(called.at(-1), 'codex-cli');
  const messages = (await json('/bots/ada/transcript')).messages;
  const delivered = messages.find((row: any) => row.role === 'assistant');
  assert.equal(delivered.tool_calls[0].function.name, 'send_message_to_user');
  assert.ok(messages.some((row: any) => row.role === 'tool' && row.content.startsWith("sent to the owner's chat")));
  assert.ok((await json('/bots/ada/context')).requests[0].prompt > 0);
  assert.ok((await json('/bots/ada')).memory.some((row: any) => row.text === '本猫记忆'));
  assert.ok(!(await json('/bots/砚砚')).memory.some((row: any) => row.text === '本猫记忆'));
  const groupResponse = await (await call('POST', '/groups', { name: '设计组', members: ['宪宪', '砚砚'] })).json() as any;
  assert.ok(groupResponse.id);
  const accepted = await call('POST', `/groups/${groupResponse.id}/messages`, { text: '一起讨论' });
  assert.equal((await accepted.json() as any).status, 'sent');
  await runtime.orchestrator.wait(groupResponse.id);
  const group = await json(`/groups/${groupResponse.id}`);
  assert.ok(group.messages.some((m: any) => m.kind === 'person' && m.text === '一起讨论'));
  assert.ok(group.messages.some((m: any) => m.sender === '砚砚'));
  assert.ok(group.messages.some((m: any) => m.text.startsWith('[action]') && m.text.includes('交给')));
  const failure = await call('POST', '/bots/ada/messages', { text: 'fail-now' });
  assert.match(await failure.text(), /event: error/);
  assert.equal((await call('POST', '/bots/ada/messages', { text: 'image', images: ['missing'] })).status, 501);
  const form = new FormData();
  form.append('file', new Blob([Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+/l9sAAAAASUVORK5CYII=', 'base64')], { type: 'image/png' }), 'avatar.png');
  assert.equal((await fetch(base + '/bots/ada/avatar', { method: 'POST', body: form })).status, 200);
  assert.equal((await json('/bots/ada')).avatar, 'custom');
  assert.equal((await call('GET', '/bots/ada/avatar')).headers.get('content-type'), 'image/png');
  const template = await json('/bots/ada/template'); template.name = 'ada-copy';
  assert.equal((await call('POST', '/bots/import', template)).status, 200);
  assert.equal((await json('/bots/ada-copy')).avatar, 'custom');
  assert.equal((await call('DELETE', '/bots/ada/avatar')).status, 200);
  assert.equal((await json('/bots/ada')).avatar, 'generated');
  const restored = new Store(runtime.store.file);
  const ada = restored.state.bots.find(b => b.name === 'ada')!;
  assert.equal(restored.xbot.bots[ada.id].avatarSeed, undefined);
  assert.equal((await json('/bots/ada')).avatar_seed, 'cat:ragdoll');
  assert.equal(restored.xbot.bots[ada.id].runtimeProvider, 'codex-cli');
  const attack = await fetch(base + '/bots', { method: 'POST', headers: { Origin: 'https://evil.example', 'Content-Type': 'application/json' }, body: JSON.stringify({ name: 'bad' }) });
  assert.equal(attack.status, 403);
  const plain = await fetch(base + '/bots', { method: 'POST', headers: { 'Content-Type': 'text/plain' }, body: JSON.stringify({ name: 'bad' }) });
  assert.equal(plain.status, 415);
  assert.equal((await call('DELETE', '/bots/ada-copy')).status, 200);
  assert.equal((await call('GET', '/bots/ada-copy')).status, 404);
});
